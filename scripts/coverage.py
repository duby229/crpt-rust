#!/usr/bin/env python3
"""CRPT engine coverage census.

Extracts every labelled construct from the ω-Tower spec (the construct table rows of
each rank file) and checks whether the engine src/ realizes it — matched by its label
(e.g. `R4.1.D1`) or its tag (e.g. `CRPT-Inst-18`). Emits a per-section census to
COVERAGE.md and prints a gap summary. Regenerate whenever the spec or engine changes:

    python3 scripts/coverage.py
"""
from __future__ import annotations
import re
import pathlib
import collections

SPEC = pathlib.Path("/home/duby229/Documents/CRPT_OMEGA_TOWER_")
ENGINE = pathlib.Path("/home/duby229/Documents/CRPT_RUST")
RANKS = ["R0", "R1", "R2", "R3", "R4", "R5", "R6", "Rω"]

ROW = re.compile(
    r"^\|\s*\*\*(Definition|Theorem|Lemma|Corollary|Remark|Axiom)\*\*\s*\|"
    r"\s*([A-Za-z0-9ω]+\.[0-9]+\.[A-Za-z]+[0-9]+)\s*\|"   # label
    r"\s*([^|]*?)\s*\|"                                      # tag column (may be empty or multi-tag)
)

Construct = collections.namedtuple("Construct", "label kind tag section rank")


def extract():
    out = []
    for rank in RANKS:
        f = SPEC / f"CRPT_OMEGA_TOWER_{rank}.md"
        for line in f.read_text(encoding="utf-8").splitlines():
            m = ROW.match(line)
            if not m:
                continue
            kind, label, tag = m.group(1), m.group(2), m.group(3).strip()
            section = ".".join(label.split(".")[:2])  # e.g. R4.1
            out.append(Construct(label, kind, tag, section, rank))
    return out


def engine_text():
    chunks = {}
    for p in (ENGINE / "src").rglob("*.rs"):
        chunks[p] = p.read_text(encoding="utf-8")
    return chunks


def tags_of(c):
    """Individual tags from the tag column — backtick-wrapped tokens, or the bare string."""
    backticked = re.findall(r"`([^`]+)`", c.tag)
    if backticked:
        return [t for t in backticked if len(t) >= 3]
    return [c.tag] if len(c.tag) >= 3 else []


def covered(c, chunks):
    """A construct is covered if its label or any of its tags appears in src/."""
    tags = tags_of(c)
    hits = []
    for p, text in chunks.items():
        if c.label in text or any(t in text for t in tags):
            hits.append(p.relative_to(ENGINE).as_posix())
    return hits


def main():
    constructs = extract()
    chunks = engine_text()
    rows = []
    gaps = []
    for c in constructs:
        hits = covered(c, chunks)
        rows.append((c, hits))
        if not hits:
            gaps.append(c)

    # ---- COVERAGE.md ----
    lines = ["# CRPT Engine — Spec Coverage Census", ""]
    lines.append(f"**{len(constructs)} labelled constructs** in the spec "
                 f"(`CRPT_OMEGA_TOWER_*`, v1.0.0-rc9). "
                 f"**{len(constructs) - len(gaps)} realized**, **{len(gaps)} gaps**. "
                 "Generated by `scripts/coverage.py`.")
    lines.append("")
    by_section = collections.OrderedDict()
    for c, hits in rows:
        by_section.setdefault(c.section, []).append((c, hits))
    for section, items in by_section.items():
        cov = sum(1 for _, h in items if h)
        lines.append(f"## {section} — {cov}/{len(items)}")
        lines.append("")
        lines.append("| Label | Kind | Tag | Realized in |")
        lines.append("|---|---|---|---|")
        for c, hits in items:
            where = ", ".join(sorted(set(hits))) if hits else "**— GAP —**"
            lines.append(f"| {c.label} | {c.kind} | `{c.tag}` | {where} |")
        lines.append("")
    (ENGINE / "COVERAGE.md").write_text("\n".join(lines), encoding="utf-8")

    # ---- console summary ----
    print(f"{len(constructs)} constructs · {len(constructs)-len(gaps)} realized · {len(gaps)} gaps")
    gap_by_rank = collections.Counter(g.rank for g in gaps)
    for rank in RANKS:
        tot = sum(1 for c in constructs if c.rank == rank)
        print(f"  {rank}: {tot - gap_by_rank[rank]}/{tot}")
    if gaps:
        print("\nGAPS:")
        for g in gaps:
            print(f"  {g.label:14} {g.kind:11} {g.tag}")


if __name__ == "__main__":
    main()
